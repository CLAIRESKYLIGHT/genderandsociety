/* ── Helper: look up a reference by number, returns formatted citation ──── */
function getRef(num) {
  return REFERENCES.find((r) => r.num === num) || null;
}

/* ── Helper: build formatted in-text superscript anchor ─────────────────── */
function refSup(num) {
  const r = getRef(num);
  if (!r) return `<sup>[${num}]</sup>`;
  const label = r.author
    ? `${r.author}${r.year ? ", " + r.year : ""}`
    : r.title;
  return `<sup><a href="#ref${num}" class="ref-anchor" title="${label}" aria-label="Sanggunian ${num}: ${label}">[${num}]</a></sup>`;
}

/* ── Helper: render a full Sanggunian block for given ref numbers ─────────── */
function renderSanggunianBlock(nums) {
  const items = nums
    .map((n) => getRef(n))
    .filter(Boolean)
    .map((r) => {
      const parts = [];
      if (r.author) parts.push(r.author);
      if (r.year) parts.push(`(${r.year})`);
      if (r.title) parts.push(`<em>${r.title}</em>`);
      if (r.publisher) parts.push(r.publisher);
      if (r.location) parts.push(r.location);
      const citation = parts.join(". ") + ".";
      const link = r.url
        ? ` <a href="${r.url}" target="_blank" rel="noopener noreferrer" class="ref-url">[Link]</a>`
        : "";
      return `<li id="ref${r.num}" class="sanggunian-item">
        <span class="ref-num">[${r.num}]</span>
        <span class="ref-citation">${citation}${link}</span>
      </li>`;
    })
    .join("\n");
  return `<div class="sanggunian-block" aria-label="Mga Sanggunian">
    <h4 class="sanggunian-heading">📚 Mga Sanggunian</h4>
    <ol class="sanggunian-list">${items}</ol>
  </div>`;
}

